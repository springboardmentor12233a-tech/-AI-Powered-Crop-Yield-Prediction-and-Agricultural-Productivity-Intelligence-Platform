from groq import Groq

from .config import GROQ_API_KEY, GROQ_MODEL


class GroqService:

    def __init__(self):

        if not GROQ_API_KEY:
            raise RuntimeError(
                "GROQ_API_KEY is not configured."
            )

        self.client = Groq(
            api_key=GROQ_API_KEY
        )

    def analyze_prediction(
        self,
        year,
        state_name,
        district_name,
        crop,
        area,
        previous_yield,
        previous_area,
        previous_production,
        predicted_yield
    ):

        prompt = f"""
You are an agricultural AI decision-support assistant.

Analyze the crop-yield prediction generated by an XGBoost
machine-learning model.

========================
INPUT DATA
========================

Crop: {crop}
State: {state_name}
District: {district_name}
Prediction Year: {year}

Current Cultivated Area: {area} ha

Previous Year Yield: {previous_yield} Kg/ha
Previous Year Area: {previous_area} ha
Previous Year Production: {previous_production}

XGBoost Predicted Yield: {predicted_yield} Kg/ha


========================
IMPORTANT RULES
========================

1. The XGBoost predicted yield is the authoritative ML output.
   DO NOT change, recalculate, or replace it.

2. Previous-year data refers to Year - 1.
   For example, if the prediction year is 2010,
   the previous-year data refers to 2009.

3. Only use the information explicitly provided above.

4. DO NOT invent or assume:
   - rainfall
   - temperature
   - soil type
   - soil fertility
   - irrigation availability
   - fertilizer usage
   - seed variety
   - pest or disease conditions
   - market prices
   - local farming practices
   - government schemes
   - weather conditions

5. If a factor is not present in the supplied data,
   clearly state:
   "Not available in the supplied data."

6. Do not present general agricultural assumptions as
   facts about this specific farm or location.

7. Clearly distinguish between:
   - ML prediction
   - interpretation
   - general recommendations

8. Do not claim that the prediction is guaranteed.

9. Do not infer whether the current cultivated area is
   planned, current, or future beyond what is explicitly
   stated in the input.

10. Do not invent historical dates or reinterpret the
    supplied year values.


========================
RESPONSE FORMAT
========================

Provide the following sections:

1. Yield Prediction Summary

State:
- Crop
- Location
- Prediction year
- Current cultivated area
- Previous-year yield
- Predicted yield

2. Prediction Interpretation

Compare the predicted yield with the previous-year yield
and explain the change using only the supplied data.

3. Available Data Insights

Explain what can actually be inferred from the supplied
features.

4. Practical Recommendations

Give general recommendations relevant to crop-yield
management, but clearly label them as general guidance
rather than location-specific facts.

5. Risks and Limitations

Explain that the prediction is an ML estimate and identify
important factors that are not included in the supplied
data.

Keep the response concise, clear, accurate, and useful
for a farmer.
"""

        response = self.client.chat.completions.create(
            model=GROQ_MODEL,
            messages=[
                {
                    "role": "system",
                    "content": (
                        "You are a careful agricultural "
                        "decision-support assistant. "
                        "Never fabricate missing data."
                    )
                },
                {
                    "role": "user",
                    "content": prompt
                }
            ],
            temperature=0.2,
            max_tokens=1200
        )

        return response.choices[0].message.content