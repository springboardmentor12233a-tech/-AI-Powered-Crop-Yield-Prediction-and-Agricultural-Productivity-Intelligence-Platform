from groq import Groq

try:
    from .config import GROQ_API_KEY, GROQ_MODEL
except ImportError:
    from config import GROQ_API_KEY, GROQ_MODEL


class GroqService:

    def __init__(self):
        if not GROQ_API_KEY:
            raise RuntimeError("GROQ_API_KEY is not configured.")

        self.client = Groq(api_key=GROQ_API_KEY, timeout=8.0, max_retries=0)
        self.model = GROQ_MODEL or "llama-3.3-70b-versatile"

    def analyze_prediction(
        self,
        year,
        state_name,
        district_name,
        crop,
        area,
        previous_yield,
        previous_area,
        previous_production,
        predicted_yield,
        language: str = "English"
    ):
        prompt = f"""
You are an expert agricultural AI decision-support assistant powered by Groq.

Analyze the crop-yield prediction generated by an XGBoost machine-learning model for a farmer.

========================
INPUT DATA
========================
Crop: {crop}
State: {state_name}
District: {district_name}
Prediction Year: {year}
Current Cultivated Area: {area} ha
Previous Year Yield: {previous_yield} Kg/ha
Previous Year Area: {previous_area} ha
Previous Year Production: {previous_production}
XGBoost Predicted Yield: {predicted_yield:.2f} Kg/ha

========================
CRITICAL MANDATORY RULES
========================
1. The XGBoost predicted yield ({predicted_yield:.2f} Kg/ha) is the authoritative ML output. You MUST NOT change, recalculate, round, or alter this numerical value under any circumstances.
2. Every single reference to the predicted yield in your output MUST state EXACTLY {predicted_yield:.2f} Kg/ha.
3. Language Instruction: Translate ALL section headers, text, tips, and explanations fully into {language}. Do NOT leave section titles in English unless {language} is English.
4. Provide simple, easy-to-understand explanations for farmers alongside detailed technical insights.
5. Previous-year data refers to Year - 1 ({year - 1}).

========================
RESPONSE FORMAT (Fully in {language})
========================
Provide clear, actionable sections fully translated in {language}:

1. 📊 Yield Prediction Summary (fully in {language})
- Crop: {crop}
- Location: {district_name}, {state_name}
- Prediction Year: {year}
- Current Cultivated Area: {area} ha
- Previous Year Yield ({year-1}): {previous_yield} Kg/ha
- Authoritative XGBoost Predicted Yield ({year}): {predicted_yield:.2f} Kg/ha

2. 🌾 Simple Explanation & Farmer Conversion (fully in {language})
- Explain in simple, friendly terms what this yield prediction ({predicted_yield:.2f} Kg/ha) means for the farmer.
- Provide approximate conversion: Yield per acre (~ {predicted_yield/2.471:.1f} Kg/acre) and 50kg bags per acre (~ {(predicted_yield/2.471)/50:.1f} bags/acre).

3. 📈 Crop Trajectory & Interpretation (fully in {language})
Compare predicted yield with historical yield ({previous_yield} vs {predicted_yield:.2f} Kg/ha) and explain key drivers.

4. 🌱 Practical Farmer Action Plan (fully in {language})
Give practical, easy step-by-step advice for {crop} in {state_name} regarding irrigation schedule, fertilizer timing, and soil health.

5. ⚠️ Risks & Simple Prevention Tips (fully in {language})
Explain weather/pest risks and simple preventive measures for farmers.
"""

        response = self.client.chat.completions.create(
            model=self.model,
            messages=[
                {
                    "role": "system",
                    "content": f"You are a helpful agricultural expert. ALWAYS generate your entire response fully translated into {language}, including all headings, bullet points, and farmer tips. Never alter the numerical predicted yield value."
                },
                {
                    "role": "user",
                    "content": prompt
                }
            ],
            temperature=0.2,
            max_tokens=700
        )

        return response.choices[0].message.content

    def translate_text(self, text: str, target_language: str) -> str:
        prompt = f"""
You are a professional agricultural translator.
Translate the following executive agricultural report completely into {target_language}.

========================
CRITICAL TRANSLATION RULES
========================
1. Retain ALL section titles, bullet points, icons (📊, 🌾, 📈, 🌱, ⚠️), and markdown formatting (bold **, headers ###, lists -).
2. Keep ALL numerical figures (especially yield {target_language} values, Kg/ha, ha, ₹, %), crop names, and location names intact.
3. Do NOT shorten, abbreviate, summarize, or omit any details. Provide a complete, faithful translation.
4. Write in clear, natural, farmer-friendly {target_language}.
5. Output ONLY the translated report text.

========================
TEXT TO TRANSLATE:
========================
{text}
"""
        response = self.client.chat.completions.create(
            model=self.model,
            messages=[
                {
                    "role": "system",
                    "content": f"You are a precise agricultural translator. Output the complete translated markdown report in {target_language} without losing any information."
                },
                {
                    "role": "user",
                    "content": prompt
                }
            ],
            temperature=0.2,
            max_tokens=1600
        )

        return response.choices[0].message.content

    def chat_assistant(self, messages, role: str = "farmer", language: str = "English"):
        formatted_messages = [
            {
                "role": "system",
                "content": (
                    f"You are AgriYield AI Assistant powered by Groq, a helpful and knowledgeable agricultural expert. "
                    f"You are assisting a {role}. Provide clear, accurate, and actionable agricultural advice in {language}."
                )
            }
        ]

        for msg in messages:
            r = "user" if msg.get("sender") == "user" or msg.get("role") == "user" else "assistant"
            txt = msg.get("text") or msg.get("content", "")
            formatted_messages.append({"role": r, "content": txt})

        response = self.client.chat.completions.create(
            model=self.model,
            messages=formatted_messages,
            temperature=0.4,
            max_tokens=1000
        )

        return response.choices[0].message.content
