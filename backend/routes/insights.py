"""
YieldSense AI — AI Insights Route (Groq LLM)
POST /ai-insights — Generate agricultural insights from Groq LLM
"""
from fastapi import APIRouter, HTTPException, Depends
import sys, os

sys.path.append(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from models.schemas import InsightsRequest, InsightsResponse
from auth_utils import get_current_user
from config import get_settings

router = APIRouter(prefix="", tags=["AI Insights"])
settings = get_settings()


def build_prompt(payload: InsightsRequest) -> str:
    fertilizer = "Yes" if payload.fertilizer_used else "No"
    irrigation = "Yes" if payload.irrigation_used else "No"
    return f"""You are an expert agricultural scientist and agronomist.

A farmer has provided the following field parameters and our machine learning model has predicted the crop yield. Please analyze these parameters and provide detailed agricultural insights.

=== FARM & CROP PARAMETERS ===
Crop              : {payload.crop}
Region            : {payload.region}
Soil Type         : {payload.soil_type}
Soil pH           : {payload.soil_ph}
Nitrogen (N)      : {payload.nitrogen} kg/ha
Phosphorus (P)    : {payload.phosphorus} kg/ha
Potassium (K)     : {payload.potassium} kg/ha
Fertilizer Used   : {fertilizer}
Irrigation Used   : {irrigation}

=== WEATHER PARAMETERS ===
Rainfall          : {payload.rainfall_mm} mm
Temperature       : {payload.temperature_c} °C
Weather Condition : {payload.weather_condition}

=== ML PREDICTION RESULT ===
Predicted Yield   : {payload.predicted_yield_kg_per_acre:.1f} kg/acre
(This yield was predicted by a machine learning model trained on historical agricultural data. Do NOT change or contradict this value.)

=== YOUR TASK ===
Please provide a comprehensive agricultural analysis with the following sections:

1. **Prediction Explanation**: Why is the yield {payload.predicted_yield_kg_per_acre:.1f} kg/acre for {payload.crop}? Explain the key factors from the data above.

2. **Soil Assessment**: Evaluate the soil conditions (pH, NPK levels, soil type) and their impact on yield.

3. **Weather Impact**: How do the rainfall ({payload.rainfall_mm} mm), temperature ({payload.temperature_c}°C), and weather condition ({payload.weather_condition}) affect this crop's yield?

4. **Farming Recommendations**: What specific actions can the farmer take to improve yield? (Be practical and actionable.)

5. **Risk Observations**: What risks or challenges should the farmer be aware of given these conditions?

Keep the response concise, practical, and farmer-friendly. Use bullet points where appropriate.
"""


@router.post("/ai-insights", response_model=InsightsResponse)
async def ai_insights(payload: InsightsRequest, current_user=Depends(get_current_user)):
    """
    Generate AI-powered agricultural insights using Groq LLM.
    The LLM explains the ML prediction and provides farming recommendations.
    NOTE: The LLM does NOT change the ML prediction value.
    """
    api_key = settings.GROQ_API_KEY.strip()

    if not api_key:
        return InsightsResponse(
            insights=(
                "AI insights are currently unavailable. "
                "Please set the GROQ_API_KEY environment variable to enable this feature. "
                "Your ML prediction result above is still valid and accurate."
            ),
            provider="Groq",
            model="N/A",
            disclaimer="LLM API key not configured. ML prediction is unaffected.",
        )

    try:
        from groq import Groq
        client = Groq(api_key=api_key)
        prompt = build_prompt(payload)

        chat_completion = client.chat.completions.create(
            messages=[
                {
                    "role": "system",
                    "content": (
                        "You are an expert agricultural scientist providing practical, "
                        "data-driven insights to farmers. Be concise and helpful."
                    ),
                },
                {"role": "user", "content": prompt},
            ],
            model="qwen/qwen3.8-27b",
            max_tokens=1024,
            temperature=0.4,
        )

        insights_text = chat_completion.choices[0].message.content

        return InsightsResponse(
            insights=insights_text,
            provider="Groq",
            model="qwen/qwen3.8-27b",
            disclaimer=(
                "These insights are generated by an AI language model for informational purposes. "
                "The yield figure shown above is from the ML prediction model and is NOT modified by the AI."
            ),
        )

    except Exception as e:
        error_msg = str(e)
        return InsightsResponse(
            insights=(
                f"AI insights temporarily unavailable: {error_msg}\n\n"
                "Your ML crop yield prediction is still valid. "
                "Please check your GROQ_API_KEY or try again later."
            ),
            provider="Groq",
            model="qwen/qwen3.8-27b",
            disclaimer="LLM API call failed. ML prediction is unaffected.",
        )
