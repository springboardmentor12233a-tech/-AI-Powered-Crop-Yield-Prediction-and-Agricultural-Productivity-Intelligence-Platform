import httpx

try:
    from .config import GEMINI_API_KEY, GEMINI_MODEL
except ImportError:
    from config import GEMINI_API_KEY, GEMINI_MODEL


class GeminiService:

    def __init__(self):
        self.api_key = GEMINI_API_KEY
        self.model = GEMINI_MODEL or "gemini-3.8-flash"

        if not self.api_key:
            print("⚠️ GEMINI_API_KEY is not set.")

    def analyze_prediction(
        self,
        year,
        state_name,
        district_name,
        crop,
        area,
        previous_yield,
        previous_area,
        previous_production,
        predicted_yield,
        language: str = "English"
    ) -> str:
        if not self.api_key:
            raise RuntimeError("GEMINI_API_KEY is not configured.")

        prompt = f"""
You are an expert Agricultural AI Advisory System powered by Google Gemini.

Analyze the crop-yield prediction generated by an XGBoost machine-learning model for a farmer.

========================
INPUT DATA
========================
Crop: {crop}
State: {state_name}
District: {district_name}
Prediction Year: {year}
Current Cultivated Area: {area} ha
Previous Year Yield: {previous_yield} Kg/ha
Previous Year Area: {previous_area} ha
Previous Year Production: {previous_production}
XGBoost Predicted Yield: {predicted_yield:.2f} Kg/ha

========================
CRITICAL MANDATORY RULES
========================
1. The XGBoost predicted yield ({predicted_yield:.2f} Kg/ha) is the authoritative ML output. You MUST NOT change, recalculate, round, or alter this numerical value under any circumstances.
2. Every single reference to the predicted yield in your output MUST state EXACTLY {predicted_yield:.2f} Kg/ha.
3. Language Instruction: Translate ALL section headers, text, tips, and explanations fully into {language}. Do NOT leave section titles in English unless {language} is English.
4. Provide simple, easy-to-understand explanations for farmers alongside detailed technical insights.
5. Previous-year data refers to Year - 1 ({year - 1}).

========================
RESPONSE FORMAT (Fully in {language})
========================
Provide clear, actionable sections fully translated in {language}:

1. 📊 Yield Prediction Summary (fully in {language})
- Crop: {crop}
- Location: {district_name}, {state_name}
- Prediction Year: {year}
- Cultivated Area: {area} ha
- Historical Yield ({year-1}): {previous_yield} Kg/ha
- Authoritative XGBoost Predicted Yield ({year}): {predicted_yield:.2f} Kg/ha

2. 🌾 Simple Explanation & Farmer Conversion (fully in {language})
- Explain in simple, friendly terms what this yield prediction ({predicted_yield:.2f} Kg/ha) means for the farmer.
- Provide approximate conversion: Yield per acre (~ {predicted_yield/2.471:.1f} Kg/acre) and 50kg bags per acre (~ {(predicted_yield/2.471)/50:.1f} bags/acre).

3. 📈 Prediction Interpretation (fully in {language})
Compare the predicted yield with the previous year yield ({previous_yield} vs {predicted_yield:.2f} Kg/ha). Explain the trajectory based on acreage and historical production.

4. 🌱 Soil & Agronomic Action Plan (fully in {language})
Give key practical recommendations for {crop} farming in {state_name} regarding irrigation, pest monitoring, fertilizer management, and soil health.

5. ⚠️ Risk Assessment & Simple Prevention (fully in {language})
List potential risks (weather, pest pressure, market volatility) and suggest preventive farmer action.

Keep the response encouraging, structured, easy to read, and empowering for the farmer in {language}.
"""
        return self._generate(prompt)

    def translate_text(self, text: str, target_language: str) -> str:
        if not self.api_key:
            raise RuntimeError("GEMINI_API_KEY is not configured.")

        prompt = f"""
You are a professional agricultural translator specializing in Indian languages.
Translate the following executive agricultural report completely into {target_language}.

========================
CRITICAL TRANSLATION RULES
========================
1. Retain ALL section titles, bullet points, icons (📊, 🌾, 📈, 🌱, ⚠️), and markdown formatting (bold **, headers ###, lists -).
2. Keep ALL numerical figures (especially yield values, Kg/ha, ha, ₹, %), crop names, and location names EXACTLY intact.
3. Do NOT shorten, summarize, abbreviate, or omit any text or recommendations.
4. Translate clearly, accurately, and fluently into natural {target_language} that a farmer can easily read.
5. Output ONLY the translated markdown report text.

========================
TEXT TO TRANSLATE:
========================
{text}
"""
        return self._generate(prompt)


    def chat_assistant(self, messages, role: str = "farmer", language: str = "English") -> str:
        if not self.api_key:
            raise RuntimeError("GEMINI_API_KEY is not configured.")

        system_instruction = (
            f"You are AgriYield AI Assistant powered by Google Gemini, a friendly, highly knowledgeable agricultural expert. "
            f"You are assisting a {role}. Provide helpful, practical, precise advice on crop yield, soil health, pest management, "
            f"irrigation, fertilizers, market prices, and sustainable farming practices. Please answer in {language}."
        )

        formatted_prompt = f"System Context: {system_instruction}\n\n"
        for msg in messages:
            sender = "User" if msg.get("sender") == "user" or msg.get("role") == "user" else "Assistant"
            text = msg.get("text") or msg.get("content", "")
            formatted_prompt += f"{sender}: {text}\n"

        formatted_prompt += "Assistant:"

        return self._generate(formatted_prompt)

    def _generate(self, prompt: str) -> str:
        # Use a bounded direct request so an unavailable provider never blocks a prediction.
        models_to_try = list(dict.fromkeys([self.model, "gemini-2.5-flash"]))
        for m in models_to_try:
            try:
                url = f"https://generativelanguage.googleapis.com/v1beta/models/{m}:generateContent?key={self.api_key}"
                resp = httpx.post(
                    url,
                    json={"contents": [{"parts": [{"text": prompt}]}]},
                    timeout=8.0
                )
                if resp.status_code == 200:
                    data = resp.json()
                    candidates = data.get("candidates", [])
                    if candidates:
                        parts = candidates[0].get("content", {}).get("parts", [])
                        if parts:
                            return parts[0].get("text", "")
            except Exception as e:
                print(f"HTTP REST attempt for model {m} failed: {e}")

        raise RuntimeError("Failed to generate response from Gemini API.")
