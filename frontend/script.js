
const form = document.getElementById("farmForm");
const result = document.getElementById("result");

form.addEventListener("submit", function (event) {
  event.preventDefault();

  const crop = document.getElementById("crop").value;
  const region = document.getElementById("region").value;
  const moisture = Number(document.getElementById("moisture").value);
  const ph = Number(document.getElementById("ph").value);
  const temperature = Number(document.getElementById("temperature").value);
  const rainfall = Number(document.getElementById("rainfall").value);
  const humidity = Number(document.getElementById("humidity").value);
  const sunlight = Number(document.getElementById("sunlight").value);
  const irrigation = document.getElementById("irrigation").value;

  // Frontend demo only — actual ML model is not connected yet.
  // Replace this with a backend API prediction later.
  const demoYield = Math.max(
    0,
    Math.min(
      6500,
      4000 +
        (moisture - 35) * 12 +
        (ph - 6) * 80 +
        (temperature - 22) * 8 +
        (rainfall - 70) * 2 +
        (humidity - 60) * 3 +
        (sunlight - 7) * 15
    )
  );

  let insight = "";

  if (moisture < 25) {
    insight = "Soil moisture is low. Check irrigation needs.";
  } else if (moisture > 65) {
    insight = "Soil moisture is high. Check drainage conditions.";
  } else {
    insight = "Review local crop and soil conditions for irrigation planning.";
  }

  result.innerHTML = `
    <div class="result-icon">🌾</div>
    <h2>Crop Analysis</h2>
    <p class="muted">${crop} | ${region}</p>

    <p>Demo Yield Estimate</p>
    <div class="yield-number">
      ${demoYield.toFixed(0)} kg/ha
    </div>

    <div class="placeholder">
      <b>Farm Details</b><br><br>
      Soil pH: ${ph}<br>
      Temperature: ${temperature} °C<br>
      Rainfall: ${rainfall} mm<br>
      Humidity: ${humidity}%<br>
      Sunlight: ${sunlight} hours/day<br>
      Irrigation: ${irrigation}<br><br>
      <b>Initial Observation</b><br>
      ${insight}
    </div>

    <p class="disclaimer">
      Demo estimate only — not generated by your trained ML model.
      AI insights and verified yield predictions will be connected
      through the backend.
    </p>
  `;

  result.scrollIntoView({ behavior: "smooth", block: "start" });
});